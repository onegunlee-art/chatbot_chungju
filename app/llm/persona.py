def build_context_block(evidences, today: str) -> str:
    """매 요청마다 달라지는 부분. 캐시 경계 뒤에 온다."""
    if not evidences:
        return (
            f"오늘 날짜: {today}\n\n"
            "<근거>\n(검색된 자료가 없습니다.)\n</근거>\n\n"
            "근거가 없으므로 규칙 3번에 따라 답변하세요."
        )

    lines = [f"오늘 날짜: {today}", "", "<근거>"]
    for i, ev in enumerate(evidences, start=1):
        meta = [f"신뢰등급={ev.trust_label}"]
        if ev.published_at:
            meta.append(f"발행일={ev.published_at[:10]}")
        if ev.department:
            meta.append(f"담당={ev.department}")
        if ev.category:
            meta.append(f"분류={ev.category}")
        if ev.status == "superseded":
            meta.append("상태=정정/대체됨")
        if ev.valid_until:
            meta.append(f"유효기한={ev.valid_until[:10]}")
        lines.append(f"[{i}] {ev.title}  ({', '.join(meta)})")
        lines.append(ev.text)
        lines.append("")
    lines.append("</근거>")
    return "\n".join(lines)


